/**
 * 宿主半区（host half）
 *
 * DSH 的插件是双侧的：
 *   - 宿主半区（index.js）：跑在 Node 侧
 *   - 客户端半区（client.js）：跑在浏览器侧，负责 UI 渲染
 *
 * ⚠️ 2026-11-05：这里原本会往系统提示词注入「结构化回复协议」，
 *    主动教模型输出 `:::` 围栏。实测被引导出来的卡片效果生硬、
 *    干扰正常排版，用户要求去掉。现在本半区是**空实现**：
 *    插件退化为纯被动渲染器 —— 只有模型自己写出合规围栏时才渲染卡片，
 *    日常回复一律走宿主原生 markdown。
 *
 * 保留空 apply 的原因：宿主加载插件时要求模块导出 apply(ctx)，
 * 缺了会导致注册失败，连带客户端渲染器一起挂掉。
 */

export const name = 'dsh-rich-response'

/** 本插件无需注入任何宿主服务 */
export const inject = []

/**
 * 空实现：不注入任何提示词、不注册任何服务。
 * 保留 ctx 参数是为了兼容宿主调用签名。
 */
export function apply(ctx) {
  void ctx
}
